const {
  withAppDelegate,
  withInfoPlist,
} = require("@expo/config-plugins");

const marker = "// @generated by curiosity-ios-scene-lifecycle";

const sceneManifest = Object.freeze({
  UIApplicationSupportsMultipleScenes: false,
  UISceneConfigurations: {
    UIWindowSceneSessionRoleApplication: [
      {
        UISceneConfigurationName: "Default Configuration",
        UISceneDelegateClassName: "$(PRODUCT_MODULE_NAME).SceneDelegate",
      },
    ],
  },
});

const windowStartup = `
#if os(iOS) || os(tvOS)
    window = UIWindow(frame: UIScreen.main.bounds)
    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: launchOptions)
#endif
`;

const sceneDelegate = `${marker}
@objc(SceneDelegate)
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard
      let windowScene = scene as? UIWindowScene,
      let appDelegate = UIApplication.shared.delegate as? AppDelegate,
      let factory = appDelegate.reactNativeFactory
    else { return }

    let window = UIWindow(windowScene: windowScene)
    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: Self.launchOptions(from: connectionOptions)
        ?? appDelegate.launchOptions)
    appDelegate.window = window
    self.window = window
  }

  func scene(_ scene: UIScene, openURLContexts contexts: Set<UIOpenURLContext>) {
    for context in contexts {
      _ = RCTLinkingManager.application(
        UIApplication.shared,
        open: context.url,
        options: [:])
    }
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    _ = RCTLinkingManager.application(
      UIApplication.shared,
      continue: userActivity,
      restorationHandler: { _ in })
  }

  private static func launchOptions(
    from connectionOptions: UIScene.ConnectionOptions
  ) -> [UIApplication.LaunchOptionsKey: Any]? {
    var launchOptions: [UIApplication.LaunchOptionsKey: Any] = [:]
    if let url = connectionOptions.urlContexts.first?.url {
      let key = UIApplication.LaunchOptionsKey(
        rawValue: "UIApplicationLaunchOptionsURLKey")
      launchOptions[key] = url
    }
    if let activity = connectionOptions.userActivities.first(where: {
      $0.activityType == NSUserActivityTypeBrowsingWeb
    }) {
      let key = UIApplication.LaunchOptionsKey(
        rawValue: "UIApplicationLaunchOptionsUserActivityDictionaryKey")
      launchOptions[key] = [
        "UIApplicationLaunchOptionsUserActivityTypeKey": activity.activityType,
        "UIApplicationLaunchOptionsUserActivityKey": activity,
      ]
    }
    return launchOptions.isEmpty ? nil : launchOptions
  }
}

`;

const patchAppDelegate = (source) => {
  if (source.includes(marker)) return source;
  if (!source.includes(windowStartup))
    throw new Error("CURIOSITY_IOS_SCENE_TEMPLATE_UNSUPPORTED");

  const factoryProperty =
    "  var reactNativeFactory: RCTReactNativeFactory?\n";
  if (!source.includes(factoryProperty))
    throw new Error("CURIOSITY_IOS_SCENE_TEMPLATE_UNSUPPORTED");

  const reactNativeDelegate = "class ReactNativeDelegate";
  if (!source.includes(reactNativeDelegate))
    throw new Error("CURIOSITY_IOS_SCENE_TEMPLATE_UNSUPPORTED");

  return source
    .replace(
      factoryProperty,
      `${factoryProperty}  var launchOptions: [UIApplication.LaunchOptionsKey: Any]?\n`,
    )
    .replace(
      "  ) -> Bool {\n    let delegate = ReactNativeDelegate()",
      "  ) -> Bool {\n    self.launchOptions = launchOptions\n    let delegate = ReactNativeDelegate()",
    )
    .replace(
      windowStartup,
      `\n    // React Native starts in SceneDelegate on iOS 27 and later SDKs.\n`,
    )
    .replace(reactNativeDelegate, `${sceneDelegate}${reactNativeDelegate}`);
};

const withIosSceneLifecycle = (config) => {
  config = withInfoPlist(config, (configured) => {
    configured.modResults.UIApplicationSceneManifest = sceneManifest;
    return configured;
  });
  return withAppDelegate(config, (configured) => {
    if (configured.modResults.language !== "swift")
      throw new Error("CURIOSITY_IOS_SCENE_TEMPLATE_UNSUPPORTED");
    configured.modResults.contents = patchAppDelegate(
      configured.modResults.contents,
    );
    return configured;
  });
};

module.exports = withIosSceneLifecycle;
module.exports.patchAppDelegate = patchAppDelegate;
module.exports.sceneManifest = sceneManifest;
